// Función para obtener preguntas aleatorias sin repetición
export function getRandomQuestions(count: number = 10): Question[] {
  // Clonamos y barajamos el banco exhaustivo completo
  const shuffled = [...MASTER_PARAGUAY_QUESTIONS];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
